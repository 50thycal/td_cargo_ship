// Writes the map rebuild round's plan doc (docs/design/v3-maps-rebuild.md)
// and one diagram per map (docs/design/v3-maps-rebuild/NN-id.svg), from the
// same data as the review page: plan.mjs, facts.mts and the results file.
// Usage: node tools/v3/maps-rebuild/plan-doc.mjs
import { mkdirSync, writeFileSync } from 'node:fs';
import { loadAll, root, origThreats, layoutLine, todayFoes, eventLine, mapNotes, pairNames, CORNER_WORD } from './lib.mjs';

const D = loadAll();
const { facts, measured, PLAN, SYSTEMS, QUESTIONS, NOTES, ROUND, SEARCHED, pairs } = D;
const DIR = 'docs/design/v3-maps-rebuild';
mkdirSync(root + DIR, { recursive: true });
const svgName = (m) => `${String(m.slot).padStart(2, '0')}-${m.id}.svg`;
for (const m of facts.maps) writeFileSync(`${root}${DIR}/${svgName(m)}`, m.svg + '\n');

const foeName = (f) => facts.foes[f].name;
const cell = (s) => String(s).replace(/\|/g, '\\|');
const WHO = { player: 'You', design: 'Design note', brief: 'Brief' };
const L = [];
const P = (...s) => L.push(...s);

P('# V3 map rebuild: the plan round', '');
P('This file is generated by `node tools/v3/maps-rebuild/plan-doc.mjs` from `tools/v3/maps-rebuild/plan.mjs` (the round\'s data), `facts.mts` (the game today) and `' + ROUND.measured + '` (the bots). Edit those, not this.', '');
P(`> "${ROUND.ask}"`, '');
P(`The ${facts.maps.length} campaign maps were laid out in the maps plan ([v3-maps-plan.md](v3-maps-plan.md), built in [v3-maps-build.md](v3-maps-build.md)), before the ${Object.keys(facts.foes).length} new enemies, the ${facts.pairs.length} enemy pairs ([v3-enemy-pairs.md](v3-enemy-pairs.md)), the events and the new weapons. This round decides how each map is rebuilt around them. Nothing in the game changes in this round.`, '');

P('## The review page', '');
P('- **Built by** `node tools/v3/maps-rebuild/page.mjs <out.html>` (it runs `facts.mts` through vite-node and refuses to build if the plan breaks its rules). It is published as an Artifact with `capabilities: {db: {}}`: https://claude.ai/artifact/652LYxsxEqVdph6vp8ab4V');
P('- **Tabs:** Scope (the questions), one per chapter (its five maps), Systems, All notes, My marks (with the "Anything else?" box).');
P('- **Checked** at 390 px and 874 px wide, light and dark, in Chromium: no console errors, no sideways scroll on any tab, a verdict saves (to the browser off claude.ai) and Bring back shows on a Cut.', '');
P('**The store** (each document is `{ ...fields, at: ISO time }`; before the store answers, marks wait in `localStorage` with `pending: true`):', '');
P('| Collection | Fields | Holds |', '|---|---|---|');
P('| `reviews/{mapId}` | `verdict` (`approve`, `change` or `cut`), `note` | A verdict on a map\'s proposal. Ids are `MAP_ORDER`\'s (`strait` … `citadel`). |');
P(`| \`systems/{id}\` | \`verdict\`, \`note\` | A verdict on a map-wide change: ${SYSTEMS.map((s) => `\`${s.id}\``).join(', ')}. |`);
P(`| \`answers/{questionId}\` | \`choice\` (option index, 0 = the recommended), \`note\` | The Scope answers: ${QUESTIONS.map((q) => `\`${q.id}\``).join(', ')}. |`);
P('| `answers/else` | `note` | The "Anything else?" box. |', '');
P('Read them back with one `ArtifactData` `list` of each collection, copy them to `tools/v3/maps-rebuild/review-<date>.json`, and count verdicts from that file.', '');

P('## How this was made', '');
P('- **Today\'s maps** come from the game\'s own data (`tools/v3/maps-rebuild/facts.mts`): each map\'s layout, the original threats each wave brings (the wave table at its threat scale, its extras and its attack vectors), the new enemies the raid planner (`planFoes`) sends wave by wave over three seeds, its debut, its event and what sits under the call-out corner. The diagrams are drawn from the live `MapDef` by `tools/v3/maps-plan/svg.ts`, with the proposed hatches and call-out corner on top.');
P(`- **Win rates** (\`tools/v3/maps-rebuild/measure.mts\`, ${measured.seeds} seeds a map, build ${measured.build}): ${measured.how}`);
P('- **The rules every proposal keeps** (`checkPlan` in `plan.mjs`): every enemy debuts once, on a map of its chapter, alone on its debut wave; no enemy or pair before its members are met; pairs from wave 6 (wave 4 on a chapter finale) and only from their chapter; the Repair Ship pairs from wave 9, Repair Ship + Bodyguard Ring once; target tries rising through each chapter and from finale to finale; each map keeps its own event.', '');

P('## Scope questions', '');
for (const [k, q] of QUESTIONS.entries()) {
  P(`${k + 1}. **${q.q}** (\`${q.id}\`)`);
  q.options.forEach((o, i) => P(`   ${i + 1}. ${o}`));
  P(`   - Why it matters: ${q.why}`);
  for (const e of D.evidence(q.id, facts, measured)) P(`   - ${e}`);
}
P('');

P('## Systems', '');
for (const s of SYSTEMS) {
  P(`### ${s.name} (\`${s.id}\`)`, '');
  P(`- **What you'd see:** ${s.see}`);
  P(`- **Why:** ${s.why}`);
  P('- **How it plugs in:**');
  for (const h of s.how) P(`  - ${h}`);
  P('');
}

P('## Measured today', '');
P(`Won the map (got through the ten waves), ${measured.seeds} seeds each. The target is the proposed tries as a win rate.`, '');
P('| # | Map | Target | Average bot, campaign Armory | Your persona, campaign Armory | Sharp bot, no Armory | Average bot, no Armory |', '|---|---|---|---|---|---|---|');
for (const m of facts.maps) {
  const r = measured.maps[m.id];
  const f = (v) => `${v.won}% (${v.through10}%)`;
  P(`| ${m.slot} | ${m.name} | ${PLAN[m.id].tries} tries (${Math.round(100 / PLAN[m.id].tries)}%) | ${f(r.campaign.average)} | ${f(r.campaign.you)} | ${f(r.empty.sharp)} | ${f(r.empty.average)} |`);
}
P('');

for (const c of facts.chapters) {
  P(`## Chapter ${c.n}: ${c.name}`, '');
  P(`New enemies: ${c.foes.map(foeName).join(', ')}. ${c.weapons.length ? `New weapons: ${c.weapons.map((w) => w.name).join(', ')}.` : ''} Pairs from this chapter: ${facts.pairs.filter((p) => p.chapter === c.n).map((p) => `${p.name} (\`${p.id}\`)`).join(', ')}.`, '');
  for (const m of facts.maps.filter((x) => x.chapter === c.n)) {
    const p = PLAN[m.id];
    const used = [...new Set(p.waves.flatMap((w) => [w.pair].flat().filter(Boolean)))];
    P(`### ${m.slot}. ${m.name} (\`${m.id}\`)`, '');
    P(`![${m.name}](v3-maps-rebuild/${svgName(m)})`, '');
    P(`**${p.identity}**`, '');
    P('**Today**', '');
    P(`- ${layoutLine(m)}`, `- ${todayFoes(m, facts)}`, `- ${eventLine(m, facts)}`);
    if (m.callout.covers.length) P(`- The call-out corner covers ${m.callout.covers.join(' and ')}.`);
    const r = measured.maps[m.id];
    P(`- Measured: the average bot with a campaign Armory won ${r.campaign.average.won}% (${r.campaign.average.through10}% through the ten waves), your persona ${r.campaign.you.won}%; with no Armory, sharp ${r.empty.sharp.won}%, average ${r.empty.average.won}%. ${p.trend}`, '');
    const notes = mapNotes(m.id, NOTES, PLAN);
    if (notes.length) {
      P('**Notes**', '');
      for (const n of notes) P(`- ${WHO[n.who]}: "${n.quote}" (${n.source})`);
      P('');
    }
    P('**The rebuild**', '');
    P(`- **Debut:** ${p.debut ? `${foeName(p.debut)}, alone on wave ${p.debutWave}.` : 'none (a chapter finale: the chapter\'s enemies and pairs).'}`);
    P(`- **Pairs:** ${used.length ? used.map((id) => `${pairs[id].name} (\`${id}\`)`).join(', ') : 'none.'}`);
    P(`- **Target:** ${p.tries} tries.`);
    P(`- **Event:** ${p.event.text}`);
    P(`- **Call-outs:** ${CORNER_WORD[p.callouts ?? 'br']}.`);
    P(`- **Layout:** ${p.layout.length ? p.layout.map((l) => `${l.what} (${l.why})`).join(' ') : 'no change.'}${p.hatches ? ` Hatches at ${p.hatches.map((h) => `(${h.x}, ${h.y})`).join(', ')}.` : ''}`, '');
    P('| Wave | Original threats (today\'s table) | New enemies | Pair | Moment |', '|---|---|---|---|---|');
    p.waves.forEach((w, k) => {
      const debut = p.debut && k + 1 === p.debutWave;
      P(`| ${k + 1} | ${cell(origThreats(m.waves[k]))} | ${w.foes.length ? w.foes.map((f) => (debut ? `**${foeName(f)}**` : foeName(f))).join(', ') : '—'} | ${pairNames(w.pair, pairs).join(' then ') || '—'} | ${cell(w.moment || '—')} |`);
    });
    P('');
  }
}

P('## Every note found', '');
P(`Searched: ${SEARCHED.join('; ')}.`, '');
for (const n of NOTES) P(`- **${WHO[n.who]}**, ${n.maps === 'all' ? 'every map' : n.maps.map((id) => D.mapById[id].name).join(', ')}: "${n.quote}" (${n.source})`);
P('');

P('## Judgement calls', '');
P('- **Debuts stay where they are today.** Each map keeps the enemy its event is built on, so the events (each tested in the Test Lab on its own map) still fit. The three maps that repeat a debut today (Harbor Mouth, Saltgate Canal, Citadel of Vey) become finales with no debut, as their events already are; Dreadnought Pass keeps the Spotter.');
P('- **The original threats are today\'s.** Each script keeps the wave table, extras and attack vectors as they are; the new enemies and pairs take their share out of it, as the planner does today. Tuning each map to its target is the build\'s job, with these rates as the start.');
P('- **Two measures.** The reaction-time bots with no Armory are what earlier rounds reported; the maps were tuned against an Armory that fills by about map 10, so the headline is the average bot and the persona fitted to your play with a campaign Armory (one upgrade a bay, level 5 × (slot − 1) / 9). Eight seeds a map is a few: a map\'s rate moves by 12.5 points a seed.');
P('- **The call-out corner** is checked with a box the stack\'s size (the right or left third of the field, its bottom 250 units). By that box the Kesh Hook, the Gauntlet and the Needle also have a base under it, beside the six the call-outs round named. The Gauntlet has one under every corner, so it fades instead.');
P('- **"Long shore road."** Every map now has a shore road crossing the screen, and the Rocket Truck uses the short pop-up roads, so no script is held back by roads. Rocket Convoy stays on the Gauntlet, with a road on each shore.');
P('- **The "6 or more new things" note** came with this round\'s brief; its words weren\'t in the repo. The count holds today (the evidence under `mr-debut`).');
P('- **The Siege Battery note** is read two ways at once: the hatch is a fixed part of the map, and the gun does not take a launch base\'s place or its missiles. If you meant only one of them, say so on the Systems card.');
P('');

writeFileSync(root + 'docs/design/v3-maps-rebuild.md', L.join('\n'));
console.log(`wrote docs/design/v3-maps-rebuild.md and ${facts.maps.length} diagrams in ${DIR}`);
