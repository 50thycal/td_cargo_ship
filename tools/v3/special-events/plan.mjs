// Writes docs/design/v3-special-events.md from events.mjs, so the plan can't
// drift from the review page.
// Usage: node tools/v3/special-events/plan.mjs [--check]
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { ROUND_DATE, ASK, TODAY, PIECES, EVENTS, QUESTIONS } from './events.mjs';

// The published review page (fill in once it is published).
const REVIEW_URL = 'https://claude.ai/artifact/Q7w8heyAgvHDPDyeR1bBbg';

const root = new URL('../../../', import.meta.url);
const out = new URL('docs/design/v3-special-events.md', root);
const NAMES = JSON.parse(execSync('npx tsx tools/v3/special-events/names.mts', { cwd: root.pathname }).toString());
const SIZE = { S: 'small', M: 'medium', L: 'large' };
const chapterName = (n) => (n ? `Chapter ${n}: ${NAMES.chapters[n]}` : 'The original threats');

const lines = [];
const L = (s = '') => lines.push(s);
L('# V3 special event attacks: the plan');
L();
L(`Design round of ${ROUND_DATE}: each map keeps its normal waves and gets one scripted special event, built on the enemy that debuts there.`);
L();
L('This file is generated by `node tools/v3/special-events/plan.mjs` from `tools/v3/special-events/events.mjs`. Edit that, not this.');
L();
L(`- **Review page:** ${REVIEW_URL}. It is built by \`node tools/v3/special-events/page.mjs <out.html>\`, with the pictures from \`node tools/v3/special-events/shots.mjs\` (needs \`npx vite preview --port 4185\` on a fresh build; writes \`docs/design/img/special-events/<eventId>.jpg\`).`);
L('- **Its store** (each document also has `at`, an ISO time):');
L();
L('| Collection | Fields | Holds |');
L('|---|---|---|');
L('| `pieces/{pieceId}` | `verdict` (approve, change or cut), `note` | A mark on a piece of the system. |');
L('| `reviews/{eventId}` | `verdict` (go, maybe or drop), `note` | A mark on an event. |');
L('| `answers/{questionId}` | `choice` (option index, 0 = recommended), `note` | An answer (`se-` ids). |');
L('| `answers/se-else` | `note` | The "Anything else?" box. |');
L();
L('## The ask');
L();
L(`> ${ASK}`);
L();
L('## What the game does today');
L();
for (const t of TODAY) L(`- ${t}`);
L();
L(`## The system (${PIECES.length} pieces)`);
L();
for (const [k, p] of PIECES.entries()) {
  L(`### ${k + 1}. ${p.name} (\`${p.id}\`)`);
  L();
  L(`- **What you'd see:** ${p.see}`);
  L(`- **Why:** ${p.why}`);
  L(`- **How:** ${p.how}`);
  L();
}
L(`## The events (${EVENTS.length})`);
L();
L('| Event | Chapter | Map | Debut enemy | Size |');
L('|---|---|---|---|---|');
for (const ch of [1, 2, 3, 4, 0]) {
  for (const e of EVENTS.filter((x) => x.chapter === ch)) {
    L(`| ${e.name}${e.player ? ' (the player\'s idea)' : ''} | ${ch || '–'} | ${e.map ? NAMES.maps[e.map] : 'Free Play, endless'} | ${e.foe ? NAMES.foes[e.foe].name : e.map ? 'the chapter\'s new enemies' : '–'} | ${e.size} |`);
  }
}
L();
for (const ch of [1, 2, 3, 4, 0]) {
  const list = EVENTS.filter((e) => e.chapter === ch);
  L(`### ${chapterName(ch)} (${list.length})`);
  L();
  for (const e of list) {
    const where = e.map ? `${NAMES.maps[e.map]} (\`${e.map}\`)` : 'Free Play, endless, later maps';
    const foe = e.foe ? `debut enemy: ${NAMES.foes[e.foe].name} (\`${e.foe}\`)` : e.map ? 'the chapter\'s new enemies' : 'the original threats';
    L(`#### ${e.name} (\`${e.id}\`)${e.player ? ': the player\'s idea' : ''}`);
    L();
    L(`*${where} · ${foe} · ${SIZE[e.size]} build.*`);
    L();
    L(e.pitch);
    L();
    if (existsSync(new URL(`docs/design/img/special-events/${e.id}.jpg`, root))) {
      L(`![${e.name}: concept over a real frame of ${NAMES.maps[e.map]}](img/special-events/${e.id}.jpg)`);
      L();
    }
    if (e.rule) L(`- **Rule while it runs:** ${e.rule}`);
    L(`- **How it plays:** ${e.how}`);
    L(`- **How you beat it:** ${e.counter}`);
    L(`- **Strong:** ${e.strong}`);
    L(`- **Weak:** ${e.weak}`);
    L();
  }
}
L(`## Questions (${QUESTIONS.length})`);
L();
L('The recommended option is first in each.');
L();
for (const q of QUESTIONS) {
  L(`- **\`${q.id}\`:** ${q.q}`);
  for (const [k, o] of q.options.entries()) L(`  ${k + 1}. ${o}`);
}
L('- **`se-else`:** Anything else? (a free note)');
L();
const md = lines.join('\n');
if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== md) {
    console.error('docs/design/v3-special-events.md is stale: run node tools/v3/special-events/plan.mjs');
    process.exit(1);
  }
  console.log('Plan doc is up to date.');
} else {
  writeFileSync(out, md);
  console.log(`Wrote ${out.pathname}`);
}
