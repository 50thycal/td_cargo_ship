// Writes docs/design/v3-enemy-build.md from build.mjs and the player's marks
// (review-2026-11-07.json), so the plan can't drift from the page.
// Usage: node tools/v3/enemy-ideas/plan.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { BUILD, BUILD_DATE, CHAPTER_NAMES, CHAPTER_WHY, READINGS, ANSWER_EFFECT, BUILD_QUESTIONS } from './build.mjs';
import { CATEGORIES, QUESTIONS } from './enemies.mjs';

const marks = JSON.parse(readFileSync(new URL('./review-2026-11-07.json', import.meta.url), 'utf8'));
const out = new URL('../../../docs/design/v3-enemy-build.md', import.meta.url);
const cat = (c) => CATEGORIES.find((x) => x.id === c);
const where = (e) => `${cat(e.cat).name} · ${cat(e.cat).subs.find((s) => s.id === e.sub).name}`;
const by = (v) => Object.entries(marks.reviews).filter(([, r]) => r.verdict === v).map(([, r]) => r.name);

const lines = [];
const L = (s = '') => lines.push(s);
L('# V3 enemy build: the plan');
L();
L(`What the player's marks on enemy round 1 ([v3-enemy-ideas.md](v3-enemy-ideas.md)) turned into, ${BUILD_DATE}. The marks are saved in \`tools/v3/enemy-ideas/review-2026-11-07.json\`.`);
L();
L('This file is generated by `node tools/v3/enemy-ideas/plan.mjs` from `tools/v3/enemy-ideas/build.mjs`. Edit that, not this.');
L();
L('- **Review page:** https://claude.ai/artifact/Sm8d5jmPVxTwihiTiKdtGX, its Build tab (the round 1 tabs stay as they were). It is built by `node tools/v3/enemy-ideas/page.mjs <out.html>`, with the screenshots from `node tools/v3/enemy-ideas/foeshots.mjs` (needs `npx vite preview --port 4173` on a fresh build). Its store:');
L('  - `builds/{enemyId}`: `verdict` (keep, tune or cut) and `note`, after playing each enemy;');
L('  - `answers/{questionId}`: `choice` and `note` for the build questions (`eb-` ids; `eb-notes` is the free note);');
L('  - round 1 stays in `reviews/` and `answers/en-*`.');
L('- **How it was checked:** [v3-enemy-build-checks.md](v3-enemy-build-checks.md).');
L();
L('## The marks');
L();
L(`- **Go further (${by('go').length}):** ${by('go').join(', ')}.`);
L(`- **Brought back (${by('revive').length}):** ${by('revive').join(', ')}.`);
L(`- **Maybe, kept for later (${by('maybe').length}):** ${by('maybe').join(', ')}.`);
L(`- **Dropped (${by('drop').length}):** ${by('drop').join(', ')}.`);
L('- **No verdict, read as Go further:** Dive Bomber (see below).');
L();
L('### The answers');
L();
for (const q of QUESTIONS) {
  const a = marks.answers[q.id];
  if (a) L(`- **${q.q}** You chose: *${a.chosen}*. ${ANSWER_EFFECT[q.id]}`);
}
L();
L('### Readings to check');
L();
for (const r of READINGS) L(`- ${r.text}`);
L();
L('## How the new enemies join the game');
L();
L('- **By chapter**, like the weapons (`src/v3/data/foes.ts`). A map in chapter *n* can send any enemy from chapters 1 to *n*. The chapter\'s own new ones come up most, and each map of the chapter leads with a different one.');
L('- **How many:** one a wave on waves 2 to 5, two on 6 to 9, three on wave 10 (more in endless). Each takes the place of a drone swarm in the wave, and the heavier ones (the platforms that fire several times, the ones that bring a heavy, the barge) a missile too, so a wave\'s weight stays close; the sweep checks it.');
L('- **Surfaced** as the weapons are: the briefing lists the chapter\'s new enemies; the first time one shows up, the "new threat" card names it and says what to do.');
L('- **Free Play** gets an Enemies line: as the campaign (the map\'s chapter), none of the new ones, all of them, or one on its own (it comes every wave, more often), to try each.');
L('- **The rule for anything you can\'t intercept** (Rocket Truck\'s rockets, Siege Battery\'s shells, the Dive Bomber\'s bomb): a tell first, and the source can always be shot.');
L();
for (const ch of [1, 2, 3, 4]) {
  const list = BUILD.filter((b) => b.chapter === ch);
  L(`## Chapter ${ch}: ${CHAPTER_NAMES[ch]} (${list.length})`);
  L();
  L(CHAPTER_WHY[ch]);
  L();
  for (const b of list) {
    L(`### ${b.name}`);
    L();
    L(`*${where(b)}.*`);
    L();
    L(`- **How it plays:** ${b.how}`);
    L(`- **The tell:** ${b.tell}`);
    L(`- **The answer:** ${b.answer}`);
    L(`- **Numbers (first proposals):** ${b.numbers}`);
    L();
  }
}
L('## Build order');
L();
L('1. **Phase 0, systems:** the roster by chapter, the waves mixing them in, the briefing and first-sight cards, the Free Play Enemies line, the play log.');
L('2. **Phases 1 to 4:** one chapter\'s enemies at a time: the sim, the drawing, sounds, the bots, tests.');
L('3. **Then:** the campaign sweep (each chapter\'s difficulty against the lock-in build), browser checks of each enemy on a phone, the docs.');
L();
L('## New questions (on the page\'s Build tab)');
L();
for (const q of BUILD_QUESTIONS) {
  L(`- **\`${q.id}\`:** ${q.q}`);
  for (const [k, o] of q.options.entries()) L(`  ${k + 1}. ${o}`);
}
L();
const md = lines.join('\n');
if (process.argv.includes('--check')) {
  if (readFileSync(out, 'utf8') !== md) {
    console.error('docs/design/v3-enemy-build.md is stale: run node tools/v3/enemy-ideas/plan.mjs');
    process.exit(1);
  }
  console.log('Plan doc is up to date.');
} else {
  writeFileSync(out, md);
  console.log(`Wrote ${out.pathname}`);
}
