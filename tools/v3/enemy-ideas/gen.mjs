// Builds docs/design/v3-enemy-ideas.md from the round's data (enemies.mjs),
// so the doc can't drift from the review page.
// Usage: node tools/v3/enemy-ideas/gen.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { ROUND_DATE, ANSWERS, PRESSURES, CATEGORIES, TODAY, PLAYER, NEW, ARSENAL, QUESTIONS } from './enemies.mjs';

const PAGE = process.env.ENEMY_PAGE_URL ?? 'https://claude.ai/artifact/Sm8d5jmPVxTwihiTiKdtGX';
const out = new URL('../../../docs/design/v3-enemy-ideas.md', import.meta.url);
const kept = NEW.filter((i) => i.status === 'keep');
const cut = NEW.filter((i) => i.status === 'cut');
const cat = (c) => CATEGORIES.find((x) => x.id === c);
const where = (e) => `${cat(e.cat).name} · ${cat(e.cat).subs.find((s) => s.id === e.sub).name}`;
const names = (ids) => ids.map((id) => ARSENAL[id]).join(', ');
const cell = (s) => String(s).replace(/\|/g, '\\|').replace(/\n+/g, ' ');

const lines = [];
const L = (s = '') => lines.push(s);
L('# V3 enemy ideas, round 1 (brainstorm, not built)');
L();
L('Nothing in this document is built. It is the enemy\'s version of the weapons\' round 2: a taxonomy, the player\'s ideas with a read on each, and new ideas, for the player to mark before any build.');
L();
L(`- **Review page:** ${PAGE}. The same ideas, each with a picture drawn over a real wave, Go further / Maybe / Drop and notes, the cut ideas (Bring back), and ${QUESTIONS.length} questions. Its saved marks are what the next session reads first:`);
L('  - `reviews/{ideaId}`: `verdict` (go, maybe, drop or revive) and `note`;');
L('  - `answers/{questionId}`: `choice` (option index) and `note`; ids start `en-`, and `en-notes` is the free note.');
L('- **Build the page:** `node tools/v3/enemy-ideas/page.mjs <out.html>`.');
L('- **The pictures:** `node tools/v3/enemy-ideas/concepts.mjs` (needs `npx vite preview --port 4173` on a fresh build).');
L('- **The check:** `node tools/v3/enemy-ideas/check.mjs`.');
L('- **How the round was checked, cycle by cycle:** [v3-enemy-ideas-cycles.md](v3-enemy-ideas-cycles.md).');
L();
L('This file is generated by `node tools/v3/enemy-ideas/gen.mjs` from `tools/v3/enemy-ideas/enemies.mjs`. Edit that, not this.');
L();
L('## The ask');
L();
L(`The player (${ROUND_DATE}):`);
L();
L('> "Alright next I think we need to do the same process we did but with the enemy weapons. We need three different types of categories and then make subcategories as well for all the weapons … Then come up with new weapons for the enemy … Pick the best from that group and then come up with 10 weapons as well that a different than this list … So you don’t have to only make them make like 20 and then pick the best from that … Be Novel and come up with new ideas and inquiries weapons so they are not just another version of another weapon"');
L();
L('## Three categories');
L();
L('Split by role, like the player\'s weapons (Active, Passive, Boost): the category says what kind of answer an enemy needs. Every enemy below is placed: today\'s, the player\'s (#N), and the ten new ones (new).');
L();
for (const c of CATEGORIES) {
  L(`### ${c.name}`);
  L();
  L(c.rule);
  L();
  L('| Subcategory | What makes it one | Enemies |');
  L('|---|---|---|');
  for (const s of c.subs) {
    const m = [
      ...TODAY.filter((e) => e.cat === c.id && e.sub === s.id).map((e) => e.name),
      ...PLAYER.filter((e) => e.cat === c.id && e.sub === s.id).map((e) => `${e.name} (#${e.n})`),
      ...kept.filter((e) => e.cat === c.id && e.sub === s.id).map((e) => `**${e.name}** (new)`),
    ];
    L(`| ${s.name} | ${cell(s.rule)} | ${m.join(', ')} |`);
  }
  L();
}
L('## How "different" was checked');
L();
L('Every enemy is tagged with what the player does about it (its **answer**) and what it takes from the player (its **pressure**). `check.mjs` fails if any kept new idea shares both tags with an enemy in the game, one of the player\'s 18, or another kept idea.');
L();
const others = [...TODAY, ...PLAYER];
const uniq = (list, k) => [...new Set(list.map((e) => e[k]))];
L(`- **Today\'s ${TODAY.length} enemies:** ${uniq(TODAY, 'answer').length} answers (${uniq(TODAY, 'answer').map((a) => ANSWERS[a].toLowerCase()).join('; ')}) and ${uniq(TODAY, 'pressure').length} pressures (${uniq(TODAY, 'pressure').map((p) => PRESSURES[p].toLowerCase()).join('; ')}).`);
L(`- **Answers only the new ideas use:** ${uniq(kept, 'answer').filter((a) => !others.some((o) => o.answer === a)).map((a) => ANSWERS[a].toLowerCase()).join('; ')}.`);
L(`- **Pressures only they use:** ${uniq(kept, 'pressure').filter((p) => !others.some((o) => o.pressure === p)).map((p) => PRESSURES[p].toLowerCase()).join('; ')}.`);
L('- An independent reviewer also read the ideas cold before the page went up (cycle 1 of the cycles doc). Two ideas were cut and four rebuilt on what it found.');
L();
L('## The player\'s 18');
L();
L('The player\'s own words are on the review page, unchanged. My read:');
L();
L('| # | Idea | Where | My read | Why |');
L('|---|---|---|---|---|');
for (const p of PLAYER) L(`| ${p.n} | ${p.name} | ${where(p)} | ${p.rec} | ${cell(p.why)} |`);
L();
L(`**Recommended picks (${PLAYER.filter((p) => p.rec === 'pick').length}):** ${PLAYER.filter((p) => p.rec === 'pick').map((p) => p.name).join(', ')}.`);
L();
L(`## The new ten (kept from ${kept.length + cut.length})`);
L();
for (const [k, i] of kept.entries()) {
  L(`### N${k + 1}. ${i.name}`);
  L();
  L(`*${i.pitch}*`);
  L();
  L(`- **Where:** ${where(i)}.`);
  L(`- **Answer:** ${ANSWERS[i.answer]}.`);
  L(`- **Takes:** ${PRESSURES[i.pressure]}.`);
  L(`- **How it plays:** ${i.how}`);
  L(`- **The decision:** ${i.decision}`);
  L(`- **The tell:** ${i.tell}`);
  L(`- **What answers it:** ${names(i.counters)}.`);
  L(`- **What's new:** ${i.novel}`);
  L(`- **Cost:** ${i.cost}. ${i.costWhy}`);
  L();
  L(`![Concept: ${i.name}](img/enemy-ideas/concept-${i.id}.jpg)`);
  L();
}
L(`## Cut (${cut.length})`);
L();
L('| Idea | Where | Pitch | Why cut |');
L('|---|---|---|---|');
for (const i of cut) L(`| ${i.name} | ${where(i)} | ${cell(i.pitch)} | ${cell(i.why)} |`);
L();
L('## Questions for the player');
L();
for (const q of QUESTIONS) {
  L(`- **\`${q.id}\`:** ${q.q}`);
  for (const [k, o] of q.options.entries()) L(`  ${k + 1}. ${o}`);
}
L();
const md = lines.join('\n');
if (process.argv.includes('--check')) {
  const now = readFileSync(out, 'utf8');
  if (now !== md) { console.error('docs/design/v3-enemy-ideas.md is stale: run node tools/v3/enemy-ideas/gen.mjs'); process.exit(1); }
  console.log('Doc is up to date.');
} else {
  writeFileSync(out, md);
  console.log(`Wrote ${out.pathname}`);
}
