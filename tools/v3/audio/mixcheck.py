"""Measure the offline mix renders (tools/v3/audio/render.ts) and write
docs/audio/mix-report.md. Exits 1 if a gate fails.

  python3 tools/v3/audio/mixcheck.py

Gates, per render:
  - no clipping: the float mix never reaches full scale
  - voices never over the cap
  - no cue plays more often than its cooldown allows
  - every alert is at least 3 LU louder than everything else over the same
    stretch (alert stem vs bed stem, K-weighted, over the alert or 1.5 s)
  - busy doesn't get louder: the loudest 3 s of play without the alerts
    (before an end-of-run sting) is within 4 LU of the calm wave's loudest
    3 s (round 4: a game's quiet stretches make any within-render swing
    large, so the comparison is calm vs busy)
"""

import json
import os
import sys

import numpy as np
import pyloudnorm
from scipy.io import wavfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../../.."))
STEMS = os.path.join(ROOT, "assets-src/audio/stems")
REPORT = os.path.join(ROOT, "docs/audio/mix-report.md")
SR = 44100


def kw(x):
    m = pyloudnorm.Meter(SR)
    y = x
    for f in m._filters.values():
        y = f.apply_filter(y)
    return y


def loud(xk, a, b):
    """Loudness (LUFS) of K-weighted stereo xk between samples a and b."""
    seg = xk[a:b]
    p = (seg ** 2).mean(axis=0).sum()
    return -0.691 + 10 * np.log10(p + 1e-15)


def short_term_max(xk):
    w, hop = 3 * SR, SR // 10
    best = -99
    for a in range(0, max(1, len(xk) - w), hop):
        best = max(best, loud(xk, a, a + w))
    return best


def main():
    names = ["calm", "busy", "win", "loss"]
    lines = ["# Mix under load\n", "Generated by `npx vite-node tools/v3/audio/render.ts` then `python3 tools/v3/audio/mixcheck.py`. Each render is 30 s of a bot game mixed with the game's own mix rules; the WAVs are in `docs/audio/renders/`.\n"]
    fails = []
    bed_max = {}
    for name in names:
        rep = json.load(open(os.path.join(STEMS, f"{name}.json")))
        _, mix = wavfile.read(os.path.join(STEMS, f"{name}.mix.wav"))
        _, alert = wavfile.read(os.path.join(STEMS, f"{name}.alert.wav"))
        _, bed = wavfile.read(os.path.join(STEMS, f"{name}.bed.wav"))
        mix, alert, bed = (a.astype(np.float64) for a in (mix, alert, bed))
        peak = np.abs(mix).max()
        clipped = int((np.abs(mix) >= 1.0).sum())
        mk, ak, bk = kw(mix), kw(alert), kw(bed)
        integ = pyloudnorm.Meter(SR).integrated_loudness(mix)
        # The spike gate is about play: the end-of-run sting is a climax.
        play_end = int(rep["endAt"] * SR) if rep.get("endAt") is not None else len(mk)
        # Measured on the bed: alerts are meant to stand out of it.
        bed_integ = pyloudnorm.Meter(SR).integrated_loudness(bed[:play_end])
        stmax = short_term_max(bk[:play_end])
        f = []
        if clipped:
            f.append(f"{clipped} clipped samples")
        if rep["voicesMax"] > rep["voiceCap"]:
            f.append(f"{rep['voicesMax']} voices > cap {rep['voiceCap']}")
        for cue, r in rep["rate"].items():
            if r["allowed"] is not None and r["maxPerSec"] > r["allowed"]:
                f.append(f"{cue} {r['maxPerSec']}/s > {r['allowed']}/s")
        bed_max[name] = stmax
        if name != "calm" and stmax - bed_max["calm"] > 4:
            f.append(f"loudest 3 s without alerts is {stmax - bed_max['calm']:.1f} LU over the calm wave's")
        alert_rows = []
        for a in rep["alerts"]:
            s0 = int(a["t"] * SR)
            s1 = min(len(mix), s0 + int(min(max(a["dur"], 0.3), 1.5) * SR))
            if s1 - s0 < SR // 10:
                continue
            la, lb = loud(ak, s0, s1), loud(bk, s0, s1)
            margin = la - lb
            ok = margin >= 3
            alert_rows.append(f"| {a['id']} | {a['t']:.1f} | {la:.1f} | {lb:.1f} | {margin:+.1f} | {'ok' if ok else 'TOO QUIET'} |")
            if not ok:
                f.append(f"{a['id']} at {a['t']:.1f} s only {margin:+.1f} LU over the bed")
        busiest = sorted(rep["rate"].items(), key=lambda kv: -kv[1]["plays"])[:8]
        lines.append(f"\n## {name}\n")
        lines.append(f"{rep['map']} seed {rep['seed']}, from wave {rep['firstWave']}" + (f", weapons {', '.join(w['id'] + ' ' + str(w['level']) for w in rep['weapons'])}" if rep["weapons"] else "") + f"; game {rep['result']}; window {rep['window'][0]:.1f}–{rep['window'][1]:.1f} s.\n")
        lines.append(f"- {rep['plays']} sounds played; most voices at once {rep['voicesMax']} (cap {rep['voiceCap']}); held back by cooldown {rep['dropped']['cooldown']}, by per-cue cap {rep['dropped']['cueCap']}, by the global cap {rep['dropped']['globalCap']} (whole game)")
        lines.append(f"- peak {20 * np.log10(peak + 1e-12):.1f} dBFS, clipped samples {clipped}; integrated {integ:.1f} LUFS; without alerts {bed_integ:.1f} LUFS, its loudest 3 s {stmax:.1f} LUFS ({stmax - bed_integ:+.1f} LU over its whole, {stmax - bed_max['calm']:+.1f} LU over the calm wave's)")
        lines.append("- busiest cues: " + ", ".join(f"{c} {r['plays']} ({r['maxPerSec']}/s max, {r["allowed"] if r["allowed"] is not None else "∞"}/s allowed)" for c, r in busiest))
        if alert_rows:
            lines.append("\n| alert | at s | alert LUFS | rest LUFS | margin LU | |\n|---|---|---|---|---|---|")
            lines.extend(alert_rows)
        lines.append(f"\n**{'PASS' if not f else 'FAIL: ' + '; '.join(f)}**\n")
        fails += [f"{name}: {x}" for x in f]
        print(f"{name}: peak {20 * np.log10(peak + 1e-12):.1f} dBFS, I {integ:.1f}, bed S max {stmax:.1f} LUFS ({stmax - bed_max["calm"]:+.1f} vs calm), alerts {len(alert_rows)}, {'PASS' if not f else 'FAIL ' + '; '.join(f)}")
    open(REPORT, "w").write("\n".join(lines) + "\n")
    sys.exit(1 if fails else 0)


if __name__ == "__main__":
    main()
